import { chromium } from 'playwright';
const out = process.argv[2];
const W = Number(process.argv[3] || 1440), H = Number(process.argv[4] || 900);
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: W, height: H }, deviceScaleFactor: 1 });
const errs = [];
p.on('pageerror', (e) => errs.push('PAGEERR ' + e.message + ' ' + (e.stack || '').split('\n')[1]));
p.on('console', (m) => m.type() === 'error' && errs.push('CONSOLE ' + m.text()));
await p.goto('http://localhost:5199/');
await p.waitForTimeout(1500);
await p.evaluate(() => document.getElementById('atelier').scrollIntoView());
await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/s1-line.png` });
const box = await p.locator('#atelier .cl__sock').nth(0).locator('.cl__img').boundingBox();
await p.mouse.click(box.x + box.width / 2, box.y + box.height / 2);
await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/s2-lifting.png` });
await p.waitForTimeout(1600);
await p.screenshot({ path: `${out}/s3-picked.png` });
console.log(JSON.stringify(await p.evaluate(() => window.__holey && { phase: window.__holey.phase, L: window.__holey.L && { W: window.__holey.L.W, H: window.__holey.L.H, pinX: window.__holey.L.pinX, imgW: window.__holey.L.imgW } })));
errs.forEach((e) => console.log(e));
await b.close();
